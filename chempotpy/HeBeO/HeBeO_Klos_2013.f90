    !> @brief Evaluate the rigid-BeO surface from Cartesian coordinates in angstrom.
    subroutine evaluate( coordinates, derivative_order, energy, gradient, coupling )
        use chempotpy_atomic_elements,      only: atomic_mass_u
        use chempotpy_internal_coordinates, only: rigid_diatom_jacobi_coordinates
        use chempotpy_units,                only: electronvolt_to_inverse_centimeter
        integer, intent(in)   :: derivative_order
        real(wp), intent(in)  :: coordinates(natoms,3)
        real(wp), intent(out) :: energy(nstates), gradient(nstates,natoms,3)
        real(wp), intent(out) :: coupling(nstates,nstates,natoms,3)
        logical               :: valid
        real(wp)              :: cosine_theta, distance_bohr, energy_inverse_centimeter
        gradient = 0.0_wp; coupling = 0.0_wp
        call rigid_diatom_jacobi_coordinates(coordinates, [atomic_mass_u('Be'), atomic_mass_u('O')], &
            & distance_bohr, cosine_theta, valid)
        if( .not. valid )then
            energy = huge(1.0_wp)
            return
        endif
        call evaluate_fit(distance_bohr, cosine_theta, energy_inverse_centimeter)
        energy(1) = energy_inverse_centimeter/electronvolt_to_inverse_centimeter
    end subroutine evaluate

    !> @brief Evaluate the released RKHS fit in inverse centimeters at one Jacobi point.
    pure subroutine evaluate_fit( distance_bohr, cosine_theta, energy_inverse_centimeter )
        use chempotpy_rkhs, only: evaluate_ts2_rp25_2d
        real(wp), intent(in)  :: distance_bohr, cosine_theta
        real(wp), intent(out) :: energy_inverse_centimeter
        real(wp)              :: point(2)
        point = [0.5_wp*(1.0_wp-cosine_theta), distance_bohr]
        call evaluate_ts2_rp25_2d(point, angular_grid, radial_grid, coefficients, energy_inverse_centimeter)
    end subroutine evaluate_fit
