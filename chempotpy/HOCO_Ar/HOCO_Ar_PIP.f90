!> @brief Implement HOCO_Ar_PIP, a potential energy surface for HOCO_Ar.
module chempotpy_hoco_ar_pip_pes
    use chempotpy_kinds, only: wp
    implicit none
    private
    public :: evaluate

    contains

    !> @brief Evaluate the HOCO_Ar_PIP potential energy surface for HOCO_Ar.
    subroutine evaluate( x, igrad, path, p, gradient_out, d )
        use chempotpy_units, only: hartree_to_electronvolt
        use chempotpy_kinds, only: wp
        implicit none
        ! number of electronic state
        integer, parameter              :: nstates = 1
        integer, parameter              :: natoms  = 5
        integer, intent(in)             :: igrad
        character(len=1024), intent(in) :: path
        real(wp), intent(in)            :: x(natoms,3)
        real(wp), intent(out)           :: p(nstates)
        real(wp), intent(out)           :: gradient_out(nstates,natoms,3)
        real(wp), intent(out)           :: d(nstates,nstates,natoms,3)
        real(wp)                        :: v
        integer                         :: iatom, idir, j, istate
        !initialize
        gradient_out = 0.e0_wp; d = 0.e0_wp
        if( igrad == 0 )then
            call pot(x, v)
            v = v*hartree_to_electronvolt
            do istate=1, nstates
                p(istate) = v
            enddo
        else
            write (*, *) 'Only energy is available'
        endif
    end subroutine evaluate
end module chempotpy_hoco_ar_pip_pes

!> @brief Expose HOCO_Ar_PIP through the Python-facing PES entry point.
subroutine pes( x, igrad, path, p, gradient_out, d )
    use chempotpy_hoco_ar_pip_pes, only: evaluate
    use chempotpy_kinds,           only: wp
    implicit none
    integer, parameter              :: natoms  = 5
    integer, parameter              :: nstates = 1
    integer, intent(in)             :: igrad
    character(len=1024), intent(in) :: path
    real(wp), intent(in)            :: x(natoms,3)
    real(wp), intent(out)           :: p(nstates)
    real(wp), intent(out)           :: gradient_out(nstates,natoms,3)
    real(wp), intent(out)           :: d(nstates,nstates,natoms,3)
    call evaluate(x, igrad, path, p, gradient_out, d)
end subroutine pes

!> @brief Evaluate pot.
subroutine pot( xyz, v )
    use bemsa,           only: evaluate_fit
    use chempotpy_kinds, only: wp
    implicit none
    real(wp), intent(in)    :: xyz(5,3)
    real(wp), intent(inout) :: v
    real(wp)                :: x(10)
    real(wp)                :: a1, a2
    a1    = 2.0
    a2    = 2.5
    x(1)  = sqrt((xyz(1,1)-xyz(2,1))**2+(xyz(1,2)-xyz(2,2))**2+(xyz(1,3)-xyz(2,3))**2)
    x(2)  = sqrt((xyz(1,1)-xyz(3,1))**2+(xyz(1,2)-xyz(3,2))**2+(xyz(1,3)-xyz(3,3))**2)
    x(3)  = sqrt((xyz(1,1)-xyz(4,1))**2+(xyz(1,2)-xyz(4,2))**2+(xyz(1,3)-xyz(4,3))**2)
    x(4)  = sqrt((xyz(1,1)-xyz(5,1))**2+(xyz(1,2)-xyz(5,2))**2+(xyz(1,3)-xyz(5,3))**2)
    x(5)  = sqrt((xyz(2,1)-xyz(3,1))**2+(xyz(2,2)-xyz(3,2))**2+(xyz(2,3)-xyz(3,3))**2)
    x(6)  = sqrt((xyz(2,1)-xyz(4,1))**2+(xyz(2,2)-xyz(4,2))**2+(xyz(2,3)-xyz(4,3))**2)
    x(7)  = sqrt((xyz(2,1)-xyz(5,1))**2+(xyz(2,2)-xyz(5,2))**2+(xyz(2,3)-xyz(5,3))**2)
    x(8)  = sqrt((xyz(3,1)-xyz(4,1))**2+(xyz(3,2)-xyz(4,2))**2+(xyz(3,3)-xyz(4,3))**2)
    x(9)  = sqrt((xyz(3,1)-xyz(5,1))**2+(xyz(3,2)-xyz(5,2))**2+(xyz(3,3)-xyz(5,3))**2)
    x(10) = sqrt((xyz(4,1)-xyz(5,1))**2+(xyz(4,2)-xyz(5,2))**2+(xyz(4,3)-xyz(5,3))**2)
    x(1)  = x(1)/0.5291772083_wp
    x(1)  = exp(-x(1)/a1)
    x(2)  = x(2)/0.5291772083_wp
    x(2)  = exp(-x(2)/a1)
    x(3)  = x(3)/0.5291772083_wp
    x(3)  = exp(-x(3)/a1)
    x(4)  = x(4)/0.5291772083_wp
    x(4)  = exp(-x(4)/a2)
    x(5)  = x(5)/0.5291772083_wp
    x(5)  = exp(-x(5)/a1)
    x(6)  = x(6)/0.5291772083_wp
    x(6)  = exp(-x(6)/a1)
    x(7)  = x(7)/0.5291772083_wp
    x(7)  = exp(-x(7)/a2)
    x(8)  = x(8)/0.5291772083_wp
    x(8)  = exp(-x(8)/a1)
    x(9)  = x(9)/0.5291772083_wp
    x(9)  = exp(-x(9)/a2)
    x(10) = x(10)/0.5291772083_wp
    x(10) = exp(-x(10)/a2)
    v     = evaluate_fit(x)
end  subroutine
