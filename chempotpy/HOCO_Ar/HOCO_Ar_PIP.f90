!> @brief Own the public evaluator for this potential energy surface.
module chempotpy_hoco_ar_pip_pes
    implicit none
    private
    public :: evaluate
    contains
    !> @brief Evaluate this surface through the modern module contract.
    subroutine evaluate( x, igrad, path, p, gradient_out, d )
        use chempotpy_legacy_units, only: legacy_hartree_to_electronvolt
        implicit none
        ! number of electronic state
        integer, parameter              :: nstates = 1
        integer, parameter              :: natoms  = 5
        integer, intent(in)             :: igrad
        character(len=1024), intent(in) :: path
        double precision, intent(in)    :: x(natoms,3)
        double precision, intent(out)   :: p(nstates)
        double precision, intent(out)   :: gradient_out(nstates,natoms,3)
        double precision, intent(out)   :: d(nstates,nstates,natoms,3)
        double precision                :: v
        integer                         :: iatom, idir, j, istate
        !initialize
        gradient_out = 0.d0; d = 0.d0
        if( igrad == 0 )then
            call pot(x, v)
            v = v*legacy_hartree_to_electronvolt
            do istate=1, nstates
                p(istate) = v
            enddo
        else
            write (*, *) 'Only energy is available'
        endif
    end subroutine evaluate
end module chempotpy_hoco_ar_pip_pes

