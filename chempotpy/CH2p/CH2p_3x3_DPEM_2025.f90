    !> @brief Evaluate the CH2+ diabatic matrix and optional Cartesian derivatives.
    subroutine evaluate( x, igrad, u, ug, status )
        use chempotpy_geometry, only: all_pair_distances, flatten_cartesian_coordinates
        use chempotpy_status,   only: chempotpy_status_t, status_derivative_unavailable, status_invalid_input
        use chempotpy_units,    only: coordinates_to_bohr, hartree_per_bohr_to_ev_per_angstrom, &
            & hartree_to_electronvolt
        implicit none
        type(chempotpy_status_t), intent(out), optional :: status
        integer, parameter    :: natoms = 3, nstates = 3
        integer, intent(in)   :: igrad
        real(wp), intent(in)  :: x(natoms,3)
        real(wp), intent(out) :: u(nstates,nstates), ug(nstates,nstates,natoms,3)
        real(wp)              :: coordinates_bohr(natoms,3), distances(3), position(9)
        real(wp)              :: diabatic_elements(6), diabatic_gradient(6,9)
        integer               :: atom, direction, flat_index
        u = 0.0_wp; ug = 0.0_wp
        if( present(status) ) call status%clear()
        if( igrad < 0.or.igrad > 1 )then
            if( present(status) ) call status%set(status_derivative_unavailable, &
                'CH2p_3x3_DPEM_2025 provides diabatic energies and first derivatives')
            return
        endif
        call coordinates_to_bohr(x, coordinates_bohr)
        call all_pair_distances(coordinates_bohr, distances)
        if( any(distances <= sqrt(tiny(1.0_wp))) )then
            if( present(status) ) call status%set(status_invalid_input, &
                'CH2p_3x3_DPEM_2025 requires distinct atomic positions')
            return
        endif
        call flatten_cartesian_coordinates(coordinates_bohr, position)
        call predict_diabatic_derivatives(position, diabatic_elements, diabatic_gradient)
        u(1,1) = diabatic_elements(1); u(1,2) = diabatic_elements(2); u(2,1) = diabatic_elements(2)
        u(2,2) = diabatic_elements(3); u(1,3) = diabatic_elements(4); u(3,1) = diabatic_elements(4)
        u(2,3) = diabatic_elements(5); u(3,2) = diabatic_elements(5); u(3,3) = diabatic_elements(6)
        u      = u*hartree_to_electronvolt
        if( igrad == 1 )then
            do atom = 1, natoms
                do direction = 1, 3
                    flat_index             = 3*(atom-1)+direction
                    ug(1,1,atom,direction) = diabatic_gradient(1,flat_index)
                    ug(1,2,atom,direction) = diabatic_gradient(2,flat_index)
                    ug(2,1,atom,direction) = diabatic_gradient(2,flat_index)
                    ug(2,2,atom,direction) = diabatic_gradient(3,flat_index)
                    ug(1,3,atom,direction) = diabatic_gradient(4,flat_index)
                    ug(3,1,atom,direction) = diabatic_gradient(4,flat_index)
                    ug(2,3,atom,direction) = diabatic_gradient(5,flat_index)
                    ug(3,2,atom,direction) = diabatic_gradient(5,flat_index)
                    ug(3,3,atom,direction) = diabatic_gradient(6,flat_index)
                enddo
            enddo
            ug = ug*hartree_per_bohr_to_ev_per_angstrom
        endif
    end subroutine evaluate

    !> @brief Evaluate the embedded three-hidden-layer network and its input Jacobian.
    subroutine evaluate_network( inp, o, der )
        implicit none
        real(wp), intent(in)  :: inp(n1)
        real(wp), intent(out) :: o(n5), der(n5,n1)
        real(wp)              :: w1(n1,n2), w2(n2,n3), w3(n3,n4), w4(n4,n5)
        real(wp)              :: b1(n2), b2(n3), b3(n4), b4(n5)
        w1 = reshape(params(1:n1*n2), [n1, n2])
        b1 = params(n1*n2+1:params1)
        w2 = reshape(params(params1+1:params1+n2*n3), [n2, n3])
        b2 = params(params1+n2*n3+1:params1+params2)
        w3 = reshape(params(params1+params2+1:params1+params2+n3*n4), [n3, n4])
        b3 = params(params1+params2+n3*n4+1:params1+params2+params3)
        w4 = reshape(params(params1+params2+params3+1:params1+params2+params3+n4*n5), [n4, n5])
        b4 = params(params1+params2+params3+n4*n5+1:params1+params2+params3+params4)
        call evaluate_three_hidden_tanh_network(inp, w1, b1, w2, b2, w3, b3, w4, b4, o, der)
    end subroutine evaluate_network

    !> @brief Evaluate the six unique diabatic elements and their Cartesian derivatives.
    subroutine predict_diabatic_derivatives( pos, ener, der )
        ! Expected order: H, H, C
        ! Output order diabatic: sigma, c12, pi, c13, c23, pi
        ! lr only of the two lower diabatic states.
        implicit none
        real(wp), parameter   :: alpha = 0.5_wp, acoup = 2.0_wp, ccoup = 10.0_wp
        real(wp), intent(in)  :: pos(9)
        real(wp), intent(out) :: ener(6), der(6,9)
        real(wp)              :: dis(3), edis(3), fi(5), cangle, sangle, &
            lr_shift(3), dcangle(9), dsangle(9), ddis(3, 9), dfi(5, 3), &
            dernet(6, 5), derlr(3, 9), &
            dfi_dpos(5, 9), coupdecay, c1, c2, dc1ddis2, dc2ddis3, dcoupdecaydpos(9)
        integer :: i
        dcoupdecaydpos = 0.0_wp
        call evaluate_angular_factors(pos, cangle, sangle, dcangle, dsangle)
        call all_pair_distances_and_jacobian(pos, dis, ddis)
        call evaluate_logistic(acoup*(dis(2) - ccoup), c1, dc1ddis2)
        call evaluate_logistic(acoup*(dis(3) - ccoup), c2, dc2ddis3)
        c1             = 1.0_wp - c1
        c2             = 1.0_wp - c2
        dc1ddis2       = -dc1ddis2 * acoup
        dc2ddis3       = -dc2ddis3 * acoup
        coupdecay      = c1 * c2
        dcoupdecaydpos = dc1ddis2 * ddis(2, :) * c2 + dc2ddis3 * ddis(3, :) * c1
        edis           = exp(-alpha * dis)
        call evaluate_features(edis, fi, dfi)
        fi = (fi - mean) / std
        call evaluate_network(fi, ener, dernet)
        call ch2p_long_range(pos, lr_shift, derlr)
        ener = (ener - 1.0) * (maxe - mine) / 2.0 + mine
        ! Derivative
        do i=1, 9
            ddis(:, i) = -alpha * ddis(:, i) * edis
        enddo
        do i=1, 3
            dfi(:, i) = dfi(:, i) / std
        enddo
        dernet   = dernet * (maxe - mine) * 0.5_wp
        dfi_dpos = matmul(dfi, ddis)
        der      = matmul(dernet, dfi_dpos)
        der(2,:) = sangle * coupdecay * der(2,:) + dsangle * ener(2) * coupdecay + sangle * ener(2) * dcoupdecaydpos
        der(4,:) = sangle * coupdecay * der(4,:) + dsangle * ener(4) * coupdecay + sangle * ener(4) * dcoupdecaydpos
        der(5,:) = cangle * coupdecay * der(5,:) + dcangle * ener(5) * coupdecay + cangle * ener(5) * dcoupdecaydpos
        der(1,:) = der(1,:) + derlr(1, :)
        der(3,:) = der(3,:) + derlr(2, :)
        der(6,:) = der(6,:) + derlr(3, :)
        ! end derivative
        ener(2) = sangle * ener(2) * coupdecay ! V12
        ener(4) = sangle * ener(4) * coupdecay ! V13
        ener(5) = cangle * ener(5) * coupdecay ! V23
        ener(1) = ener(1) + lr_shift(1) - release_energy_shift
        ener(3) = ener(3) + lr_shift(2) - release_energy_shift
        ener(6) = ener(6) + lr_shift(3) - release_energy_shift
    end subroutine predict_diabatic_derivatives

    !> @brief Build the five permutation-invariant neural-network features and derivatives.
    pure subroutine evaluate_features( edis, fi, dfi_dedis )
        implicit none
        real(wp), intent(in)  :: edis(3)
        real(wp), intent(out) :: fi(5), dfi_dedis(5,3)
        real(wp)              :: edis2(3)
        ! Compute edis2 = edis * edis
        edis2 = edis * edis
        ! Initialize fi and dfi_dedis
        fi        = 0._wp
        dfi_dedis = 0._wp
        ! Compute fi and its derivatives
        fi(1)          = edis(2) + edis(3)
        dfi_dedis(1,2) = 1._wp
        dfi_dedis(1,3) = 1._wp
        fi(2)          = edis2(2) + edis2(3)
        dfi_dedis(2,2) = 2._wp * edis(2)
        dfi_dedis(2,3) = 2._wp * edis(3)
        fi(3)          = edis(2) * edis(3)
        dfi_dedis(3,2) = edis(3)
        dfi_dedis(3,3) = edis(2)
        fi(4)          = edis(1) * (edis2(2) + edis2(3))
        dfi_dedis(4,1) = edis2(2) + edis2(3)
        dfi_dedis(4,2) = 2._wp * edis(1) * edis(2)
        dfi_dedis(4,3) = 2._wp * edis(1) * edis(3)
        fi(5)          = edis(1)
        dfi_dedis(5,1) = 1._wp
    end subroutine evaluate_features

    !> @brief Evaluate the signed angular factors and their Cartesian derivatives.
    pure subroutine evaluate_angular_factors( pos, cangle, sangle, dcangle_dpos, dsangle_dpos )
        implicit none
        real(wp), intent(in)  :: pos(9)
        real(wp), intent(out) :: cangle, sangle, dcangle_dpos(9), dsangle_dpos(9)
        real(wp)              :: r1(3), r2(3), n1, n2, rr(3)
        real(wp)              :: dr1_dpos(9), dr2_dpos(9), dn1_dr1(3), dn2_dr2(3)
        real(wp)              :: dcangle_dr1(3), dcangle_dr2(3), dsangle_dcangle
        ! Initialize derivatives
        dcangle_dpos = 0._wp
        dsangle_dpos = 0._wp
        ! Compute r1, r2, and rr
        r1 = pos(4:6) - pos(1:3)
        rr = pos(4:6) + pos(1:3)
        r2 = pos(7:9) - rr / 2._wp
        ! Compute norms n1 and n2
        n1 = sqrt(sum(r1 * r1)) + 1e-10
        n2 = sqrt(sum(r2 * r2)) + 1e-10
        ! Compute cangle
        cangle = sum(r1 * r2) / (n1 * n2)
        if( abs(cangle) > 1._wp ) cangle = sign(1._wp, cangle)
        ! Compute sangle
        sangle = sqrt(1._wp - cangle * cangle)
        ! Derivatives of r1 and r2 with respect to pos
        dr1_dpos(1:3) = -1._wp
        dr1_dpos(4:6) = 1._wp
        dr1_dpos(7:9) = 0._wp
        dr2_dpos(1:3) = -0.5_wp
        dr2_dpos(4:6) = -0.5_wp
        dr2_dpos(7:9) = 1._wp
        ! Derivatives of n1 and n2 with respect to r1 and r2
        dn1_dr1 = r1 / n1
        dn2_dr2 = r2 / n2
        ! Derivatives of cangle with respect to r1 and r2
        dcangle_dr1 = (r2 / (n1 * n2)) - (cangle * dn1_dr1 / n1)
        dcangle_dr2 = (r1 / (n1 * n2)) - (cangle * dn2_dr2 / n2)
        ! Derivatives of cangle with respect to pos
        dcangle_dpos(1:3) = dcangle_dr1 * dr1_dpos(1:3) + dcangle_dr2 * dr2_dpos(1:3)
        dcangle_dpos(4:6) = dcangle_dr1 * dr1_dpos(4:6) + dcangle_dr2 * dr2_dpos(4:6)
        dcangle_dpos(7:9) = dcangle_dr1 * dr1_dpos(7:9) + dcangle_dr2 * dr2_dpos(7:9)
        ! Derivative of sangle with respect to cangle
        if( abs(cangle) < 1._wp )then
            dsangle_dcangle = -cangle / sangle
        else
            dsangle_dcangle = 0._wp
        endif
        ! Derivatives of sangle with respect to pos
        dsangle_dpos = dsangle_dcangle * dcangle_dpos
    end subroutine evaluate_angular_factors

    !> @brief Evaluate a logistic switching function and its argument derivative.
    pure subroutine evaluate_logistic( x, y, dydx )
        implicit none
        real(wp), intent(in)  :: x
        real(wp), intent(out) :: y, dydx
        y    = 1.0_wp/(1.0_wp+exp(-x))
        dydx = y*(1.0_wp-y)
    end subroutine evaluate_logistic
end module chempotpy_ch2p_3x3_dpem_2025_pes

