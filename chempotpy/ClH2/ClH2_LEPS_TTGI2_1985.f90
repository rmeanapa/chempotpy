!> @brief Implement ClH2_LEPS_TTGI2_1985, a potential energy surface for ClH2.
module chempotpy_clh2_leps_ttgi2_1985_pes
    use chempotpy_kinds, only: wp
    implicit none
    private
    public :: evaluate

    contains

    !> @brief Evaluate the ClH2_LEPS_TTGI2_1985 potential energy surface for ClH2.
    subroutine evaluate( x, igrad, path, p, g, d )
        use chempotpy_units,              only: hartree_per_bohr_to_ev_per_angstrom
        use chempotpy_geometry,           only: flatten_cartesian_coordinates, transform_internal_gradient_to_cartesian
        use chempotpy_units,              only: bohr_to_angstrom, hartree_to_electronvolt
        use chempotpy_legacy_coordinates, only: triatomic_distances_to_bohr
        use chempotpy_kinds,              only: wp
        implicit none
        ! number of electronic state
        integer, parameter              :: nstates = 1
        integer, parameter              :: natoms  = 3
        integer, intent(in)             :: igrad
        character(len=1024), intent(in) :: path
        real(wp), intent(in)            :: x(natoms,3)
        real(wp), intent(out)           :: p(nstates), g(nstates,natoms,3)
        real(wp), intent(out)           :: d(nstates,nstates,natoms,3)
        real(wp)                        :: dq(3), q(3), r2(3), tx(9), dedx(9), drdx(3,9), v, xter
        integer                         :: iatom, idir, istate, j
        !initialize
        v = 0.e0_wp; g = 0.e0_wp; d = 0.e0_wp
        call flatten_cartesian_coordinates(x, tx)
        ! input cartesian is ClHH
        call triatomic_distances_to_bohr(x, q)
        dq = 0.e0_wp
        call pot(q, igrad, xter, dq)
        xter = xter*hartree_to_electronvolt
        dq   = dq*hartree_per_bohr_to_ev_per_angstrom
        r2   = q*bohr_to_angstrom
        call evdrdx(tx, r2, drdx)
        call transform_internal_gradient_to_cartesian(dq, drdx, dedx)
        if( igrad == 0 )then
            do istate=1, nstates
                p(istate) = xter
            enddo
        elseif( igrad == 1 )then
            do istate=1, nstates
                p(istate) = xter
            enddo
            do iatom=1, natoms
                do idir=1, 3
                    j               = (iatom-1)*3+idir
                    g(1,iatom,idir) = dedx(j)
                enddo
            enddo
        elseif( igrad == 2 )then
            write (*, *) 'Only energy and gradient are available'
        endif
    end subroutine evaluate
end module chempotpy_clh2_leps_ttgi2_1985_pes

!> @brief Expose ClH2_LEPS_TTGI2_1985 through the Python-facing PES entry point.
subroutine pes( x, igrad, path, p, g, d )
    use chempotpy_clh2_leps_ttgi2_1985_pes, only: evaluate
    use chempotpy_kinds,                    only: wp
    implicit none
    integer, parameter              :: natoms  = 3
    integer, parameter              :: nstates = 1
    integer, intent(in)             :: igrad
    character(len=1024), intent(in) :: path
    real(wp), intent(in)            :: x(natoms,3)
    real(wp), intent(out)           :: p(nstates)
    real(wp), intent(out)           :: g(nstates,natoms,3)
    real(wp), intent(out)           :: d(nstates,nstates,natoms,3)
    call evaluate(x, igrad, path, p, g, d)
end subroutine pes

!> @brief Evaluate EvdRdX for the ClH2_LEPS_TTGI2_1985 potential.
subroutine evdrdx( x, r, drdx )
    use chempotpy_geometry, only: ordered_pair_distance_jacobian
    use chempotpy_kinds,    only: wp
    implicit none
    integer, parameter    :: first_atoms(3)  = [1, 2, 1]
    integer, parameter    :: second_atoms(3) = [2, 3, 3]
    real(wp), intent(in)  :: x(9), r(3)
    real(wp), intent(out) :: drdx(3,9)
    call ordered_pair_distance_jacobian(x, first_atoms, second_atoms, r, drdx)
end subroutine evdrdx

