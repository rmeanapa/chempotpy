!> @brief Implement CH3OH_PIP, a potential energy surface for CH3OH.
module chempotpy_ch3oh_pip_pes
    use chempotpy_kinds, only: wp
    implicit none
    private
    public :: evaluate

    contains

    !> @brief Evaluate the CH3OH_PIP potential energy surface for CH3OH.
    subroutine evaluate( x, igrad, path, p, g, d )
        use pes_shell,       only: calcpot
        use chempotpy_units, only: bohr_to_angstrom, hartree_to_electronvolt
        use chempotpy_kinds, only: wp
        implicit none
        ! number of electronic state
        integer, parameter              :: nstates = 1
        integer, parameter              :: natoms  = 6
        integer, intent(in)             :: igrad
        character(len=1024), intent(in) :: path
        real(wp), intent(in)            :: x(natoms,3)
        real(wp), intent(out)           :: p(nstates), g(nstates,natoms,3)
        real(wp), intent(out)           :: d(nstates,nstates,natoms,3)
        real(wp)                        :: v, tx(3,natoms)
        integer                         :: iatom, idir, j, istate
        !initialize
        v = 0.e0_wp; g = 0.e0_wp; d = 0.e0_wp
        do iatom=1, natoms
            do idir=1, 3
                tx(idir,iatom) = x(iatom,idir)/bohr_to_angstrom
            enddo
        enddo
        if( igrad == 0 )then
            call calcpot(v, tx)
        else
            write (*, *) 'Only energy is available'
        endif
        !employ the minimum to be -115.57493896563480 hartree.
        v = (v+115.57493896563480)*hartree_to_electronvolt
        do istate=1, nstates
            p(istate) = v
        enddo
    end subroutine evaluate
end module chempotpy_ch3oh_pip_pes

!> @brief Expose CH3OH_PIP through the Python-facing PES entry point.
subroutine pes( x, igrad, path, p, g, d )
    use chempotpy_ch3oh_pip_pes, only: evaluate
    use chempotpy_kinds,         only: wp
    implicit none
    integer, parameter              :: natoms  = 6
    integer, parameter              :: nstates = 1
    integer, intent(in)             :: igrad
    character(len=1024), intent(in) :: path
    real(wp), intent(in)            :: x(natoms,3)
    real(wp), intent(out)           :: p(nstates)
    real(wp), intent(out)           :: g(nstates,natoms,3)
    real(wp), intent(out)           :: d(nstates,nstates,natoms,3)
    call evaluate(x, igrad, path, p, g, d)
end subroutine pes
