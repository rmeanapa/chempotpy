    !> @brief Evaluate potshell.
    subroutine potshell( xn, v )
        real(wp) :: f0, gf0(0:2,0:5)
        real(wp) :: v, xn(0:2,0:5)
        real(wp) :: d0(0:5,0:5), dw(0:5,0:5)
