        f0 = dot_product(coefficients, vec)
        v  = f0
    end subroutine potshell

    !> @brief Evaluate getd0.
    subroutine getd0 ( nk, r0, d0 )
        integer  :: nk
        real(wp) :: r0(0:nk-1,0:nk-1), d0(0:nk-1,0:nk-1)
        integer  :: i, j
        do i = 0, nk-1
            d0(i,i) = 0
            do j = i+1, nk-1
                d0(i,j) = exp(-r0(i,j)/3)
                d0(j,i) = d0(i,j)
            enddo
        enddo
    end subroutine getd0

    !> @brief Evaluate getr0.
    subroutine getr0 ( nk, xn, r0 )
        integer  :: nk
        real(wp) :: xn(0:2,0:nk-1), r0(0:nk-1,0:nk-1)
        integer  :: i, j
        do i = 0, nk-1
            r0(i,i) = 0
            do j = i+1, nk-1
                r0(i,j) = sqrt((xn(0,j)-xn(0,i))**2+(xn(1,j)-xn(1,i))**2+ (xn(2,j)-xn(2,i))**2)
                r0(j,i) = r0(i,j)
            enddo
        enddo
    end subroutine getr0

    !> @brief Evaluate getrvec.
    subroutine getrvec ( ms, r, vec )
        ! version for X4YZ
        integer            :: ms
        integer, parameter :: nk = 6
        real(wp)           :: r(0:nk-1,0:nk-1), vec(0:ms-1)
        integer            :: i, j
        real(wp)           :: x(0:3), r1(0:nk-1,0:nk-1), t0, t1
        ! Test for compatibility
        if( .not.(ms .eq. 1.or.ms .eq. 5) )then
            stop 'getrvec - wrong dimension'
        endif
        ! Computation
        x = 0
        do i = 0, nk-1
            do j = 0, nk-1
                if( i .eq. j )then
                    r1(i,j) = 0
                else
                    r1(i,j) = exp(-r(i,j))/r(i,j)
                endif
            enddo
        enddo
        ! XX distance
        t0 = 0
        do i = 0, nk-3
            do j = i+1, nk-3
                t0 = t0+r1(i,j)
            enddo
        enddo
        x(0) = t0/((nk-2)*(nk-3)/2)
        ! XY and XZ distances
        t0 = 0 ; t1 = 0
        do i = 0, nk-3
            t0 = t0+r1(i,nk-2)
            t1 = t1+r1(i,nk-1)
        enddo
        x(1) = t0/(nk-2)
        x(2) = t1/(nk-2)
        ! YZ distance
        x(3) = r1(nk-2,nk-1)
        ! set vec
        vec(0) = 1
        if( 5 .le. ms )then
            vec(1:4) = x
        endif
    end subroutine getrvec

    !> @brief Evaluate getvec.
    subroutine getvec ( ms, mr, xn, vec )
        ! version for H4CO (reordering of CH3OH).
        integer            :: ms, mr
        integer, parameter :: nk = 6
        real(wp)           :: xn(0:2,0:nk-1), vec(0:ms+4*mr-1)
        integer            :: k, l
        real(wp)           :: rvec(0:4), d0(0:nk-1,0:nk-1), r0(0:nk-1,0:nk-1)
        vec = 0
        call getr0 (nk, xn, r0)
        call getd0 (nk, r0, d0)
        call getv_x4yz (ms, d0, vec(0:ms-1))
        call getrvec (5, r0, rvec)
        do l = 0, mr-1
            do k = 0, 3
                vec(ms+4*l+k) = rvec(k+1)*vec(l)
            enddo
        enddo
    end subroutine getvec

