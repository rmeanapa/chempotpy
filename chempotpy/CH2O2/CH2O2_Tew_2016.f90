            do i = 1, ng3d
                do j = 1, 3
                    ii   = ig3d(j,i)
                    r(j) = dist(ii)
                enddo
                call f_gauss(3, r, g3d(1,i), g3d(4,i), g3d(7,i), gg)
                do j = 1, 3
                    ii       = ig3d(j,i)
                    gint(ii) = gint(ii)+gg(j)
                enddo
            enddo
            do i = 1, ng4d
                do j = 1, 4
                    ii   = ig4d(j,i)
                    r(j) = dist(ii)
                enddo
                call f_gauss(4, r, g4d(1,i), g4d(5,i), g4d(9,i), gg)
                do j = 1, 4
                    ii       = ig4d(j,i)
                    gint(ii) = gint(ii)+gg(j)
                enddo
            enddo
            do i = 1, 3*natoms
                do j = 1, ndist
                    g(i) = g(i) + b(j,i) * gint(j)
                enddo
            enddo
        endif
        if( iopt .ge. 2 )then
            h    = 0.0_wp
            hint = 0.0_wp
            do i = 1, nmorse
                ii   = imorse(i)
                r(1) = dist(ii)
                call h_morse(morse(1,i), morse(2,i), morse(3,i), r(1), hh(1))
                ij       = (ii-1)*ii/2 + ii
                hint(ij) = hint(ij)+hh(1)
            enddo
            do i = 1, ng1d
                ii   = ig1d(i)
                r(1) = dist(ii)
                call h_gauss(1, r, g1d(1,i), g1d(2,i), g1d(3,i), hh)
                ij       = (ii-1)*ii/2 + ii
                hint(ij) = hint(ij)+hh(1)
            enddo
            do i = 1, ng2d
                do j = 1, 2
                    ii   = ig2d(j,i)
                    r(j) = dist(ii)
                enddo
                call h_gauss(2, r, g2d(1,i), g2d(3,i), g2d(5,i), hh)
                ij = 0
                do j = 1, 2
                    do k = 1, j
                        ij = ij+1
                        ii = ig2d(j,i)
                        jj = ig2d(k,i)
                        call iorder(jj, ii)
                        kl       = (ii-1)*ii/2 + jj
                        hint(kl) = hint(kl)+hh(ij)
                    enddo
                enddo
            enddo
            do i = 1, ng3d
                do j = 1, 3
                    ii   = ig3d(j,i)
                    r(j) = dist(ii)
                enddo
                call h_gauss(3, r, g3d(1,i), g3d(4,i), g3d(7,i), hh)
                ij = 0
                do j = 1, 3
                    do k = 1, j
                        ij = ij+1
                        ii = ig3d(j,i)
                        jj = ig3d(k,i)
                        call iorder(jj, ii)
                        kl       = (ii-1)*ii/2 + jj
                        hint(kl) = hint(kl)+hh(ij)
                    enddo
                enddo
            enddo
            do i = 1, ng4d
                do j = 1, 4
                    ii   = ig4d(j,i)
                    r(j) = dist(ii)
                enddo
                call h_gauss(4, r, g4d(1,i), g4d(5,i), g4d(9,i), hh)
                ij = 0
                do j = 1, 4
                    do k = 1, j
                        ij = ij+1
                        ii = ig4d(j,i)
                        jj = ig4d(k,i)
                        call iorder(jj, ii)
                        kl       = (ii-1)*ii/2 + jj
                        hint(kl) = hint(kl)+hh(ij)
                    enddo
                enddo
            enddo
            ij = 0
            do i = 1, 3*natoms
                do j = 1, i
                    ij = ij +1
                    do k = 1, ndist
                        h(ij) = h(ij) + db(k,j,i) * gint(k)
                    enddo
                enddo
            enddo
            ! reuse dB as scratch
            db(:,:,1) = 0.0_wp
            do j = 1, 3*natoms
                kl = 0
                do k = 1, ndist
                    do l = 1, k-1
                        kl        = kl+1
                        db(k,j,1) = db(k,j,1) + hint(kl) * b(l,j)
                        db(l,j,1) = db(l,j,1) + hint(kl) * b(k,j)
                    enddo
                    kl        = kl+1
                    db(k,j,1) = db(k,j,1) + hint(kl) * b(k,j)
                enddo
            enddo
            ij = 0
            do i = 1, 3*natoms
                do j = 1, i
                    ij = ij + 1
                    do k = 1, ndist
                        h(ij) = h(ij) + b(k,i) * db(k,j,1)
                    enddo
                enddo
            enddo
        endif
    end subroutine evaluate_native

    !> @brief Evaluate v_morse for the CH2O2_Tew_2016 analytic potential.
    subroutine v_morse( re, al, de, r, v )
        !       Purpose: Evaluate V(r) = De**2*(1-exp(-alpha*(r-re)))**2       !
        real(wp), intent(in)  :: al, re, de, r
        real(wp), intent(out) :: v
        v = al*(re-r)
        v = exp(v) - 1.0_wp
        v = (de*v)**2
    end subroutine v_morse

    !> @brief Evaluate f_morse for the CH2O2_Tew_2016 analytic potential.
    subroutine f_morse( re, al, de, r, f )
        !       Purpose: Evaluate -dV(r)/dr  = dV(r)/d re
        real(wp), intent(in)  :: al, re, de, r
        real(wp), intent(out) :: f
        f = al*(re-r)
        f = exp(f)
        f = f*(f-1.0_wp)
        f = f*2.0_wp*al*de**2
    end subroutine f_morse

    !> @brief Evaluate h_morse for the CH2O2_Tew_2016 analytic potential.
    subroutine h_morse( re, al, de, r, h )
        !       Purpose: Evaluate d2V(r)/dr2
        real(wp), intent(in)  :: al, re, de, r
        real(wp), intent(out) :: h
        h = al*(re-r)
        h = exp(h)
        h = h*(2.0_wp*h-1.0_wp)
        h = h*2.0_wp*al**2*de**2
    end subroutine h_morse

    !> @brief Evaluate v_gauss for the CH2O2_Tew_2016 analytic potential.
    subroutine v_gauss( ndim, r, x, alpha, d, shift, v )
        !       Purpose: Evaluate V(r) = D ( exp(- 0.5 a rx**2 ) - shift )
        integer, intent(in)   :: ndim
        real(wp), intent(in)  :: r(ndim), alpha(ndim), x(ndim), d, shift
        real(wp), intent(out) :: v
        integer               :: i
        v = 0.0_wp
        do i = 1, ndim
            v = v + (r(i)-x(i))**2 * alpha(i)
        enddo
        v = v*0.5_wp
        v = exp(-v) - shift
        v = v*d
    end subroutine v_gauss

    !> @brief Evaluate f_gauss for the CH2O2_Tew_2016 analytic potential.
    subroutine f_gauss( ndim, r, x, alpha, d, v )
        !       Purpose: Evaluate dV/dr
        integer, intent(in)   :: ndim
        real(wp), intent(in)  :: r(ndim), alpha(ndim), x(ndim), d
        real(wp), intent(out) :: v(ndim)
        real(wp)              :: vv
        integer               :: i
        vv = 0.0_wp
        do i = 1, ndim
            vv = vv + (r(i)-x(i))**2 * alpha(i)
        enddo
        vv = vv*0.5_wp
        vv = exp(-vv)
        vv = vv*d
        do i = 1, ndim
            v(i) = - vv * (r(i)-x(i)) * alpha(i)
        enddo
    end subroutine f_gauss

    !> @brief Evaluate h_gauss for the CH2O2_Tew_2016 analytic potential.
    subroutine h_gauss( ndim, r, x, alpha, d, h )
        !       Purpose: Evaluate d2V/dr2
        integer, intent(in)   :: ndim
        real(wp), intent(in)  :: r(ndim), alpha(ndim), x(ndim), d
        real(wp), intent(out) :: h(ndim*(ndim+1)/2)
        real(wp)              :: vv, fi
        integer               :: i, j, ij
        vv = 0.0_wp
        do i = 1, ndim
            vv = vv + (r(i)-x(i))**2 * alpha(i)
        enddo
        vv = vv*0.5_wp
        vv = exp(-vv)
        vv = vv*d
        ij = 0
        do i = 1, ndim
            fi = (r(i)-x(i)) * alpha(i)
            do j = 1, i
                ij    = ij+1
                h(ij) = vv * fi * (r(j)-x(j)) * alpha(j)
            enddo
            h(ij) = h(ij) - alpha(i) * vv
        enddo
    end subroutine h_gauss

    !> @brief Evaluate iorder for the CH2O2_Tew_2016 analytic potential.
    subroutine iorder( i, j )
        ! permute i,j such that i < j
        implicit none
        integer :: i, j, k
        if( i .le. j ) return
        k = i
        i = j
        j = k
    end subroutine iorder
