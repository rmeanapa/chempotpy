#!/usr/bin/env python3
"""Generate the Fortran and Python CODATA constant modules."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
CORE_ROOT = REPOSITORY_ROOT / "chempotpy" / "core"
MANIFEST = CORE_ROOT / "codata_2022.json"
FORTRAN_OUTPUT = CORE_ROOT / "chempotpy_physical_constants.f90"
PYTHON_OUTPUT = CORE_ROOT / "python" / "constants.py"


def load_manifest() -> dict:
    """Load the authoritative decimal strings and provenance metadata."""

    return json.loads(MANIFEST.read_text())


def fortran_source(document: dict) -> str:
    """Render the CODATA values at the selected Fortran working precision."""

    constants = document["constants"]
    name_width = max(len(name) for name in constants)
    declarations = "\n".join(
        "    real(wp), parameter, public :: {name:<{width}} = {value}_wp".format(
            name=name, width=name_width, value=value
        )
        for name, value in constants.items()
    )
    return """!> @brief Provide the NIST CODATA 2022 constants used by CHEMPOTPY.
module chempotpy_physical_constants
    use chempotpy_kinds, only: wp
    implicit none
    private
    integer, parameter, public          :: codata_adjustment_year = {year}
    character(len=*), parameter, public :: codata_source_name     = &
        \"{source_name}\"
    character(len=*), parameter, public :: codata_source_url = &
        \"{source_url}\"
{declarations}
end module chempotpy_physical_constants
""".format(
        year=document["adjustment_year"],
        source_name=document["source_name"],
        source_url=document["source_url"],
        declarations=declarations,
    )


def python_source(document: dict) -> str:
    """Render the CODATA values as Python binary64 constants."""

    constants = document["constants"]
    declarations = "\n".join(
        "{} = {}".format(name.upper(), value)
        for name, value in constants.items()
    )
    return '''"""NIST CODATA 2022 constants used by CHEMPOTPY.

Generated by ``scripts/generate_physical_constants.py`` from the committed
decimal manifest. Do not edit this file independently.
"""

CODATA_ADJUSTMENT_YEAR = {year}
CODATA_SOURCE_NAME = "{source_name}"
CODATA_SOURCE_URL = "{source_url}"

{declarations}
'''.format(
        year=document["adjustment_year"],
        source_name=document["source_name"],
        source_url=document["source_url"],
        declarations=declarations,
    )


def update_or_check(path: Path, expected: str, check: bool) -> bool:
    """Write one generated file or report whether it is current."""

    if check:
        return path.is_file() and path.read_text() == expected
    path.write_text(expected)
    return True


def main() -> int:
    """Generate the constant modules or verify committed generated files."""

    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    document = load_manifest()
    outputs = (
        (FORTRAN_OUTPUT, fortran_source(document)),
        (PYTHON_OUTPUT, python_source(document)),
    )
    stale = [
        path for path, content in outputs
        if not update_or_check(path, content, arguments.check)
    ]
    if stale:
        for path in stale:
            print("stale generated constants: {}".format(path))
        return 1
    if arguments.check:
        print("generated physical constants are current")
    else:
        for path, _ in outputs:
            print("generated: {}".format(path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
